"""Regenerate the frozen character map using the compatibility reference oracle."""

# ruff: noqa: INP001

import hashlib
import sys
from pathlib import Path

import rapidfuzz
from rapidfuzz.utils_cpp import default_process

REFERENCE_VERSION = "3.14.6"


def main() -> None:
    if rapidfuzz.__version__ != REFERENCE_VERSION:
        raise SystemExit(f"Expected RapidFuzz {REFERENCE_VERSION}")
    ranges: list[tuple[int, int, int]] = []
    digest = hashlib.sha256()
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF:
            continue
        mapped = default_process("a" + chr(code) + "a")[1:-1]
        if len(mapped) != 1:
            raise SystemExit(f"Unexpected mapping for U+{code:04X}")
        value = ord(mapped)
        digest.update(value.to_bytes(4, "little"))
        if value == 32:
            continue
        delta = value - code
        if ranges and ranges[-1][1] == code - 1 and ranges[-1][2] == delta:
            start, _, _ = ranges[-1]
            ranges[-1] = (start, code, delta)
        else:
            ranges.append((code, code, delta))
    output = Path(__file__).resolve().parents[1] / "native/fuzzy/src/normalization.rs"
    output.write_text(
        "// Generated by scripts/generate_fuzzy_normalization.py; do not edit.\n"
        "// Oracle: RapidFuzz 3.14.6 utils_cpp at d7a98944001b88567377e3e5bc9a7f4d3d3e1f2b.\n"
        f"// SHA256 of little-endian scalar mappings: {digest.hexdigest()}\n"
        "pub const RANGES: &[(u32, u32, i32)] = &[\n"
        + "".join(
            f"    (0x{start:X}, 0x{end:X}, {delta}),\n" for start, end, delta in ranges
        )
        + "];\n",
    )
    sys.stdout.write(f"Wrote {len(ranges)} ranges to {output}\n")


if __name__ == "__main__":
    main()
